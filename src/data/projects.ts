export type Metric = {
  value: string;
  label: string;
  // 측정 근거: 실측 데이터인지, 운영팀 추정인지, 범위·상태 정보인지
  basis: string;
};

export type Flow = {
  before: { label: string; steps: string[] };
  after: { label: string; steps: string[] };
};

export type Screen = {
  src: string;
  width: number;
  height: number;
  alt: string;
  caption: string;
  // 갤러리에서 번호 대신 보여줄 이름 (예: Before, After)
  label?: string;
};

export type Table = {
  headers: string[];
  rows: string[][];
  // 강조할 행 인덱스
  highlight?: number;
  note?: string;
};

export type DailyChart = {
  title: string;
  unit: string;
  // [MM-DD, 값] — 월이 바뀌는 지점에서 색과 평균선이 나뉩니다
  points: [string, number][];
  // 표시할 메모 (예: 연휴)
  annotations?: { from: string; to: string; label: string }[];
  // 같은 날짜 축으로 위에 작게 붙이는 보조 그래프 (단위가 달라 한 축에 겹치지 않음)
  companion?: { title: string; unit: string; values: number[] };
  note?: string;
};

// 항목 몇 개를 가로 막대로 비교 (예: 회차별 미배송률)
export type CompareChart = {
  title: string;
  unit: string;
  items: { label: string; value: number; detail?: string }[];
  note?: string;
};

// 항목마다 두 그룹을 나란히 비교 (예: 사유별 새벽 vs 당일 미배송률)
export type GroupedChart = {
  title: string;
  unit: string;
  // 강조할 그룹이 첫 번째
  series: [string, string];
  rows: { label: string; values: [number, number] }[];
  note?: string;
};

export type Block = {
  heading?: string;
  body?: string;
  bullets?: string[];
  table?: Table;
  flow?: Flow;
  chart?: DailyChart;
  compare?: CompareChart;
  grouped?: GroupedChart;
  // 블록 설명을 보여주는 화면: 개선 전·후 비교, 단일 화면
  screens?: { before: Screen; after: Screen };
  image?: Screen;
  // 여러 화면을 순서대로 (모바일 화면은 가로로 나란히, 가로로 긴 화면은 위아래로)
  gallery?: Screen[];
};

export type Detail = {
  role: string;
  period: string;
  scope: string;
  deliverables: string;
  metrics: Metric[];
  what: Block[];
  why: Block[];
  how: Block[];
  tradeoffs: string[];
  result: Block[];
  // 문단이 여러 개면 배열로
  retro?: string | string[];
};

export type Project = {
  slug: string;
  title: string;
  category: string;
  summary: string;
  year: string;
  tag?: string;
  detail?: Detail;
};

