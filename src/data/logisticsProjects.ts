// 원본 객체를 건드리지 않도록 상세 내용을 새 배열로 복사해 덧붙임
export const logisticsDetails: Project[] = projects.map((project) => {
  const add = extra[project.slug];
  if (!add || !project.detail) return project;
  return {
    ...project,
    detail: {
      ...project.detail,
      how: [...project.detail.how, add.how],
      result: [...project.detail.result.filter((block) => block.heading !== add.replace), add.result],
    },
  };
});

export function getLogisticsProject(slug: string) {
  return logisticsDetails.find((project) => project.slug === slug);
}
